import { GrammyError, type Api } from "grammy";
import type { User } from "grammy/types";
import { config } from "./config.js";

const PRIVILEGED_STATUSES = new Set([
  "creator",
  "administrator",
  "member",
  "restricted",
]);

const MEMBER_LIKE_STATUSES = new Set(["creator", "administrator", "member"]);

export async function isChannelMember(api: Api, userId: number): Promise<boolean> {
  try {
    const member = await api.getChatMember(config.channelId, userId);
    return MEMBER_LIKE_STATUSES.has(member.status);
  } catch (err) {
    if (err instanceof GrammyError) {
      // user_not_found — точно не подписан
      if (err.error_code === 400) return false;
    }
    throw err;
  }
}

export async function isAdminAnywhere(api: Api, userId: number): Promise<boolean> {
  for (const chatId of [config.chatId, config.channelId]) {
    try {
      const member = await api.getChatMember(chatId, userId);
      if (member.status === "creator" || member.status === "administrator") {
        return true;
      }
    } catch {
      // игнорируем — например, пользователь не находится в чате
    }
  }
  return false;
}

export interface RiskAssessment {
  shouldBan: boolean;
  reasons: string[];
}

const SUSPICIOUS_NAME_PATTERNS: RegExp[] = [
  /^[A-Za-zА-Яа-яЁё]+\d{3,}$/u, // Имя + 3+ цифр в конце
  /^[A-Z][a-z]+[A-Z][a-z]+\d+$/u, // CamelCaseЦифры
  /^\d{4,}$/u, // одни цифры
];

function looksAutogenerated(name: string): boolean {
  const trimmed = name.trim();
  if (trimmed.length === 0) return false;
  return SUSPICIOUS_NAME_PATTERNS.some((re) => re.test(trimmed));
}

export async function computeRisk(api: Api, user: User): Promise<RiskAssessment> {
  const reasons: string[] = [];

  const subscribed = await isChannelMember(api, user.id);
  if (!subscribed) reasons.push("не подписан на канал");

  if (!user.username) reasons.push("нет username");

  const fullName = [user.first_name, user.last_name].filter(Boolean).join(" ");
  if (looksAutogenerated(fullName)) {
    reasons.push("сгенерированное имя");
  }

  // Главное правило: бан, если не подписан. Остальное — для лога/контекста.
  const shouldBan = reasons.includes("не подписан на канал");

  return { shouldBan, reasons };
}

export interface BanOutcome {
  bannedInChat: boolean;
  bannedInChannel: boolean;
  errors: string[];
}

export async function banEverywhere(api: Api, userId: number): Promise<BanOutcome> {
  const outcome: BanOutcome = {
    bannedInChat: false,
    bannedInChannel: false,
    errors: [],
  };

  try {
    await api.banChatMember(config.chatId, userId, { revoke_messages: true });
    outcome.bannedInChat = true;
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    outcome.errors.push(`бан в чате: ${msg}`);
  }

  try {
    await api.banChatMember(config.channelId, userId);
    outcome.bannedInChannel = true;
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    outcome.errors.push(`бан в канале: ${msg}`);
  }

  return outcome;
}

