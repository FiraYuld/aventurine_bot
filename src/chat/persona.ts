/**
 * Несколько заготовленных реплик в стиле персонажа о достижении суточного лимита.
 * Используются без LLM, чтобы:
 *   - не тратить лишние токены,
 *   - не зависеть от доступности API.
 */
const LIMIT_LINES: readonly string[] = [
  "У этого стола на сегодня кончились фишки для разговора с особой моего калибра. Загляни завтра — банк откроется.",
  "Ставки на сегодня закрыты: твой лимит на общение со мной исчерпан. Пережди раунд, я тоже не каменный.",
  "Дорогой я не по чеку — по настроению. А на сегодня твой кредит исчерпан. Возвращайся с рассветом.",
  "Крупье объявляет перерыв: лимит диалогов со мной на сегодня выбит. Береги шансы на завтра.",
  "Фишки — штука конечная, даже у меня. На сегодня ты своё выиграл, приходи с новой раздачей завтра.",
];

export function pickLimitLine(seed?: number): string {
  if (LIMIT_LINES.length === 0) return "Лимит на сегодня.";
  const idx =
    seed === undefined
      ? Math.floor(Math.random() * LIMIT_LINES.length)
      : Math.abs(seed) % LIMIT_LINES.length;
  return LIMIT_LINES[idx] ?? LIMIT_LINES[0]!;
}

